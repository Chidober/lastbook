#!/usr/bin/env bash
# Interactive Ubuntu Docker deploy for Lastbook + remote LM Studio (token auth).
# Usage (from repo root or this folder):
#   bash docker/deploy.sh
set -euo pipefail

ROOT="$(cd "$(dirname "$0")/.." && pwd)"
DOCKER_DIR="$ROOT/docker"
ENV_FILE="$DOCKER_DIR/lmstudio.env"
COMPOSE_FILE="$DOCKER_DIR/compose.yml"
LIBS_FILE="$DOCKER_DIR/compose.libraries.yml"

# Published pack sizes (download). Free space ≈ download + unpack (+ margin).
PACK_DOWNLOAD_GB_small="7.7"
PACK_FREE_GB_small="16"
PACK_DOWNLOAD_GB_medium="67.5"
PACK_FREE_GB_medium="140"
PACK_DOWNLOAD_GB_all="388"
PACK_FREE_GB_all="780"

die() { echo "错误: $*" >&2; exit 1; }
info() { echo "→ $*"; }
ok() { echo "✓ $*"; }

need_cmd() {
  command -v "$1" >/dev/null 2>&1 || die "需要命令: $1"
}

prompt() {
  # prompt VAR "问题" "默认值"
  local var="$1" msg="$2" def="${3-}"
  local ans
  if [ -n "$def" ]; then
    read -r -p "$msg [$def]: " ans || true
    ans="${ans:-$def}"
  else
    while true; do
      read -r -p "$msg: " ans || true
      [ -n "$ans" ] && break
      echo "  （不能为空）"
    done
  fi
  printf -v "$var" '%s' "$ans"
}

prompt_secret() {
  local var="$1" msg="$2"
  local ans
  while true; do
    read -r -s -p "$msg: " ans || true
    echo
    [ -n "$ans" ] && break
    echo "  （不能为空）"
  done
  printf -v "$var" '%s' "$ans"
}

normalize_url() {
  local u="$1"
  u="${u%/}"
  case "$u" in
    http://*|https://*) ;;
    *) u="http://$u" ;;
  esac
  # allow host:port → http://host:port
  printf '%s' "$u"
}

disk_free_gb() {
  local path="$1"
  df -BG --output=avail "$path" 2>/dev/null | awk 'NR==2{gsub(/G/,"",$1); print $1}' \
    || df -g "$path" 2>/dev/null | awk 'NR==2{print $4}' \
    || echo "?"
}

fetch_models() {
  local url="$1" token="$2"
  curl -fsS --connect-timeout 5 --max-time 20 \
    -H "Authorization: Bearer ${token}" \
    "${url}/v1/models" 2>/dev/null || true
}

pick_model() {
  local url="$1" token="$2" json ids i n choice
  json="$(fetch_models "$url" "$token")"
  if [ -z "$json" ]; then
    echo "  无法从 LM Studio 拉取模型列表（网络、地址或 token 可能不对）。请手动输入模型 id。"
    prompt SURVIVAL_MODEL "模型名称（/v1/models 里的 id）"
    return
  fi
  ids="$(printf '%s' "$json" | python3 -c '
import json,sys
try:
    d=json.load(sys.stdin)
    for m in d.get("data") or []:
        i=m.get("id")
        if i: print(i)
except Exception:
    pass
' 2>/dev/null || true)"
  if [ -z "$ids" ]; then
    echo "  模型列表为空，请手动输入。"
    prompt SURVIVAL_MODEL "模型名称"
    return
  fi
  echo
  echo "  LM Studio 上可用的模型："
  n=0
  while IFS= read -r line; do
    n=$((n + 1))
    MODEL_IDS[$n]="$line"
    echo "    $n) $line"
  done <<< "$ids"
  echo "    0) 手动输入"
  while true; do
    read -r -p "  选择编号: " choice || true
    if [ "$choice" = "0" ]; then
      prompt SURVIVAL_MODEL "模型名称"
      return
    fi
    if [[ "$choice" =~ ^[0-9]+$ ]] && [ -n "${MODEL_IDS[$choice]:-}" ]; then
      SURVIVAL_MODEL="${MODEL_IDS[$choice]}"
      return
    fi
    echo "  无效选择"
  done
}

write_env() {
  umask 077
  # Quote every value. LASTBOOK_PACK can be "small all"; an unquoted space breaks the next source.
  python3 - "$ENV_FILE" <<'PY'
import os, sys
path = sys.argv[1]
keys = [
    "LASTBOOK_CONFIG_HOST", "LMSTUDIO_URL", "LMSTUDIO_TOKEN", "SURVIVAL_MODEL",
    "SURVIVAL_REASONING_EFFORT", "LASTBOOK_PORT", "LASTBOOK_LAN", "LASTBOOK_PACK",
]
def q(v):
    return '"' + v.replace("\\", "\\\\").replace('"', '\\"').replace("$", "\\$").replace("`", "\\`") + '"'
lines = ["# Generated by docker/deploy.sh — do not commit"]
for k in keys:
    lines.append(f"{k}={q(os.environ.get(k, ''))}")
open(path, "w", encoding="utf-8").write("\n".join(lines) + "\n")
PY
  ok "已写入 $ENV_FILE"
}

wait_http() {
  local url="$1" tries="${2:-60}"
  local i=0
  while [ "$i" -lt "$tries" ]; do
    if curl -fsS --connect-timeout 1 --max-time 2 "$url" >/dev/null 2>&1; then
      return 0
    fi
    i=$((i + 1))
    sleep 1
  done
  return 1
}

pack_need_gb() {
  case "$1" in
    small) echo "$PACK_FREE_GB_small" ;;
    medium) echo "$PACK_FREE_GB_medium" ;;
    all) echo "$PACK_FREE_GB_all" ;;
    *) echo 1 ;;
  esac
}

# -------------------- main --------------------
clear 2>/dev/null || true
cat <<'BANNER'
╔══════════════════════════════════════════════╗
║     Lastbook Docker 部署向导 (Ubuntu)        ║
║  远程 LM Studio + Token · 可选资源包下载     ║
╚══════════════════════════════════════════════╝
BANNER
echo

need_cmd docker
need_cmd curl
need_cmd python3
docker compose version >/dev/null 2>&1 || die "需要 Docker Compose v2（docker compose）"

declare -A MODEL_IDS=()

# Load previous answers as defaults (except token).
PREV_URL="http://192.168.1.11:1234"
PREV_MODEL=""
PREV_PORT="8890"
PREV_LAN="0"
PREV_PACK=""
PREV_CONFIG="$ROOT/data/config"
PREV_EFFORT="none"
declare -A PREV_LIB_PATH=()
if [ -f "$ENV_FILE" ]; then
  # shellcheck disable=SC1090
  set -a; source "$ENV_FILE"; set +a
  PREV_URL="${LMSTUDIO_URL:-$PREV_URL}"
  PREV_MODEL="${SURVIVAL_MODEL:-}"
  PREV_PORT="${LASTBOOK_PORT:-$PREV_PORT}"
  PREV_LAN="${LASTBOOK_LAN:-$PREV_LAN}"
  PREV_PACK="${LASTBOOK_PACK:-$PREV_PACK}"
  PREV_CONFIG="${LASTBOOK_CONFIG_HOST:-$PREV_CONFIG}"
  PREV_EFFORT="${SURVIVAL_REASONING_EFFORT:-$PREV_EFFORT}"
  info "检测到已有配置，将作为默认值（token 需重新输入）"
  echo
fi
if [ -f "$LIBS_FILE" ]; then
  while IFS=$'\t' read -r id path; do
    [ -n "$id" ] && PREV_LIB_PATH[$id]="$path"
  done < <(python3 -c '
import json, pathlib, re, sys
text = pathlib.Path(sys.argv[1]).read_text(encoding="utf-8")
for raw in re.findall(r"^\s+-\s+(.+)$", text, re.M):
    spec = json.loads(raw) if raw[:1] == "\"" else raw
    host, _, inside = spec.partition(":")
    m = re.search(r"/libraries/([A-Za-z0-9_-]+)$", inside)
    if m and host:
        print(m.group(1) + "\t" + host)
' "$LIBS_FILE")
fi

echo "【1/5】LM Studio"
prompt LMSTUDIO_URL "LM Studio 地址（如 http://192.168.1.11:1234）" "$PREV_URL"
LMSTUDIO_URL="$(normalize_url "$LMSTUDIO_URL")"
prompt_secret LMSTUDIO_TOKEN "API Token（输入时不回显）"

info "探测 LM Studio…"
if curl -fsS --connect-timeout 5 --max-time 15 \
    -H "Authorization: Bearer ${LMSTUDIO_TOKEN}" \
    "${LMSTUDIO_URL}/v1/models" >/tmp/lastbook-lms-models.json 2>/dev/null; then
  ok "已连通 ${LMSTUDIO_URL}"
else
  echo "  警告: 当前无法访问 ${LMSTUDIO_URL}/v1/models"
  read -r -p "  仍继续？[y/N]: " cont || true
  [[ "${cont:-}" =~ ^[Yy]$ ]] || die "已取消"
fi

echo
echo "【2/5】模型名称"
if [ -n "$PREV_MODEL" ]; then
  prompt SURVIVAL_MODEL "模型 id" "$PREV_MODEL"
else
  pick_model "$LMSTUDIO_URL" "$LMSTUDIO_TOKEN"
fi
ok "模型: $SURVIVAL_MODEL"

echo
echo "【3/5】服务端口"
prompt LASTBOOK_PORT "本机开放端口（浏览器访问 http://127.0.0.1:端口）" "$PREV_PORT"
[[ "$LASTBOOK_PORT" =~ ^[0-9]+$ ]] && [ "$LASTBOOK_PORT" -ge 1 ] && [ "$LASTBOOK_PORT" -le 65535 ] \
  || die "端口无效: $LASTBOOK_PORT"

echo
echo "【4/5】要下载的图书馆（可多选）"
cat <<EOF
  空格分隔编号。每个库单独挂载，压缩包直接解压进该目录。
  1) small   约 ${PACK_DOWNLOAD_GB_small} GB（建议空闲 ≥ ${PACK_FREE_GB_small} GB）
  2) medium  约 ${PACK_DOWNLOAD_GB_medium} GB（建议空闲 ≥ ${PACK_FREE_GB_medium} GB）
  3) all     约 ${PACK_DOWNLOAD_GB_all} GB（建议空闲 ≥ ${PACK_FREE_GB_all} GB）
  回车沿用上次选择；输入 none 表示不下载，只挂载已有目录
EOF
read -r -p "  选择（例如 1 3；回车沿用上次${PREV_PACK:+: $PREV_PACK}；none=不下载）: " pack_picks || true
if [ -z "${pack_picks:-}" ]; then
  pack_picks="${PREV_PACK:-none}"
fi
PACK_IDS=()
declare -A PACK_SEEN=()
if [ "$pack_picks" != "none" ]; then
  for n in $pack_picks; do
    case "$n" in
      1|small) id=small ;;
      2|medium) id=medium ;;
      3|all) id=all ;;
      *) die "无效选择: $n" ;;
    esac
    [ -n "${PACK_SEEN[$id]:-}" ] && continue
    PACK_SEEN[$id]=1
    PACK_IDS+=("$id")
  done
fi
if [ "${#PACK_IDS[@]}" -eq 0 ]; then
  PACK_IDS=("local")
  info "不下载，挂载一个已有图书馆目录"
fi
LASTBOOK_PACK="${PACK_IDS[*]}"
ok "资源: $LASTBOOK_PACK"

echo
echo "【5/5】每个库的本机目录"
declare -a PACK_PATHS=()
idx=0
for id in "${PACK_IDS[@]}"; do
  def="${PREV_LIB_PATH[$id]:-$ROOT/data/$id}"
  prompt one "「$id」挂载目录" "$def"
  case "$one" in
    /*) ;;
    *) one="$ROOT/${one#./}" ;;
  esac
  [ "$one" != "/" ] || die "不能挂载根目录"
  mkdir -p "$one" || die "无法创建 $one"
  PACK_PATHS[$idx]="$one"
  FREE_NOW="$(disk_free_gb "$one")"
  NEED_GB="$(pack_need_gb "$id")"
  info "$id → $one （约剩余 ${FREE_NOW} GB，建议 ≥ ${NEED_GB} GB）"
  FREE_INT="${FREE_NOW%%.*}"
  if [ "$id" != "local" ] && [ "$FREE_INT" != "?" ] && [ "$FREE_INT" -lt "$NEED_GB" ] 2>/dev/null; then
    echo "  警告: 空闲空间可能不够放下 $id 。"
    read -r -p "  仍使用这个目录？[y/N]: " cont || true
    [[ "${cont:-}" =~ ^[Yy]$ ]] || die "已取消"
  fi
  if [ -s "$one/library-data/catalog.json" ]; then
    info "该目录已有图书馆，下载时会跳过"
  fi
  idx=$((idx + 1))
done
prompt LASTBOOK_CONFIG_HOST "配置目录（切换记录）" "$PREV_CONFIG"
case "$LASTBOOK_CONFIG_HOST" in
  /*) ;;
  *) LASTBOOK_CONFIG_HOST="$ROOT/${LASTBOOK_CONFIG_HOST#./}" ;;
esac
mkdir -p "$LASTBOOK_CONFIG_HOST" || die "无法创建配置目录"
prompt ACTIVE_LIB "启动时打开哪个库" "${PACK_IDS[0]}"
ACTIVE_LIB="$(printf '%s' "$ACTIVE_LIB" | tr '[:upper:]' '[:lower:]')"

read -r -p "允许局域网手机访问？(打印 ?key= 链接) [y/N]: " lan_ans || true
if [[ "${lan_ans:-}" =~ ^[Yy]$ ]]; then
  LASTBOOK_LAN=1
else
  LASTBOOK_LAN=0
fi

prompt SURVIVAL_REASONING_EFFORT "reasoning_effort（思考模型建议 none）" "$PREV_EFFORT"

echo
echo "──────── 确认 ────────"
echo "  LM Studio : $LMSTUDIO_URL"
echo "  Token     : ********"
echo "  模型      : $SURVIVAL_MODEL"
echo "  端口      : $LASTBOOK_PORT"
i=0
for id in "${PACK_IDS[@]}"; do
  echo "  挂载      : $id  ${PACK_PATHS[$i]}  →  /libraries/$id"
  i=$((i + 1))
done
echo "  启动库    : $ACTIVE_LIB"
echo "  配置目录  : $LASTBOOK_CONFIG_HOST"
echo "  局域网    : $LASTBOOK_LAN"
echo "────────────────────"
read -r -p "开始下载并启动？[Y/n]: " go || true
[[ "${go:-Y}" =~ ^[Yy]$ ]] || die "已取消"

python3 - "$LASTBOOK_CONFIG_HOST/libraries.json" "$LIBS_FILE" "$ACTIVE_LIB" "${PACK_IDS[@]}" -- "${PACK_PATHS[@]}" <<'PY'
import json, sys
from pathlib import Path
args = sys.argv[1:]
sep = args.index("--")
cfg, yml, active, *ids = args[:sep]
paths = args[sep + 1:]
if active not in ids:
    sys.exit(f"启动库 {active} 不在所选列表里")
libs = [{"id": i, "title": i[:1].upper() + i[1:], "path": f"/libraries/{i}"} for i in ids]
Path(cfg).write_text(json.dumps({"active": active, "libraries": libs}, indent=1) + "\n", encoding="utf-8")
lines = ["services:", "  lastbook:", "    volumes:"]
def spec(host, inside):
    return json.dumps(host + ":" + inside)
lines.append("      - " + spec(cfg.rsplit("/", 1)[0], "/data/config"))
for i, host in zip(ids, paths):
    lines.append("      - " + spec(host, f"/libraries/{i}"))
Path(yml).write_text("\n".join(lines) + "\n", encoding="utf-8")
print(yml)
PY

write_env

info "后台构建镜像，同时下载资源…"
(cd "$ROOT" && docker compose -f "$COMPOSE_FILE" -f "$LIBS_FILE" --env-file "$ENV_FILE" build) &
BUILD_PID=$!

i=0
for id in "${PACK_IDS[@]}"; do
  if [ "$id" != "local" ]; then
    info "下载 $id 到 ${PACK_PATHS[$i]}"
    python3 "$ROOT/docker/fetch_pack.py" --pack "$id" --dest "${PACK_PATHS[$i]}"
  fi
  i=$((i + 1))
done

wait "$BUILD_PID" || die "镜像构建失败"
info "启动容器…"
(cd "$ROOT" && docker compose -f "$COMPOSE_FILE" -f "$LIBS_FILE" --env-file "$ENV_FILE" up -d --no-build)

info "等待服务就绪…"
if wait_http "http://127.0.0.1:${LASTBOOK_PORT}/" 120; then
  ok "服务已监听 http://127.0.0.1:${LASTBOOK_PORT}/"
else
  echo
  echo "======== 容器未能在端口 ${LASTBOOK_PORT} 提供服务 ========"
  docker ps -a --filter name=lastbook || true
  echo "-------- docker logs lastbook (tail) --------"
  docker logs --tail 120 lastbook 2>&1 || true
  echo "=========================================================="
  die "服务未启动。请根据上方日志排查后重跑: bash docker/deploy.sh"
fi

echo
ok "部署完成"
echo
echo "  打开:     http://127.0.0.1:${LASTBOOK_PORT}/"
echo "  切换:     侧栏 Library 下拉框（多于一个库时出现）"
echo "  状态:     curl -s http://127.0.0.1:${LASTBOOK_PORT}/api/libraries | python3 -m json.tool"
echo "  日志:     docker logs -f lastbook"
echo "  停用:     docker compose -f docker/compose.yml -f docker/compose.libraries.yml --env-file docker/lmstudio.env down"
echo
if [ "$LASTBOOK_LAN" = "1" ]; then
  echo "  局域网密钥链接见: docker logs lastbook 2>&1 | grep 'Phones on this network'"
fi
