#!/usr/bin/env bash
# Interactive Ubuntu Docker deploy for Lastbook + remote LM Studio (token auth).
# Usage (from repo root or this folder):
#   bash docker/deploy.sh
set -euo pipefail

ROOT="$(cd "$(dirname "$0")/.." && pwd)"
DOCKER_DIR="$ROOT/docker"
ENV_FILE="$DOCKER_DIR/lmstudio.env"
COMPOSE_FILE="$DOCKER_DIR/compose.yml"

# Published pack sizes (download). Free space ≈ download + unpack (+ margin).
PACK_DOWNLOAD_GB_small="7.7"
PACK_FREE_GB_small="16"
PACK_DOWNLOAD_GB_medium="67.5"
PACK_FREE_GB_medium="140"
PACK_DOWNLOAD_GB_all="388"
PACK_FREE_GB_all="780"

die() { echo "错误: $*" >&2; exit 1; }
info() { echo "→ $*"; }
ok() { echo "✓ $*"; }

need_cmd() {
  command -v "$1" >/dev/null 2>&1 || die "需要命令: $1"
}

prompt() {
  # prompt VAR "问题" "默认值"
  local var="$1" msg="$2" def="${3-}"
  local ans
  if [ -n "$def" ]; then
    read -r -p "$msg [$def]: " ans || true
    ans="${ans:-$def}"
  else
    while true; do
      read -r -p "$msg: " ans || true
      [ -n "$ans" ] && break
      echo "  （不能为空）"
    done
  fi
  printf -v "$var" '%s' "$ans"
}

prompt_secret() {
  local var="$1" msg="$2"
  local ans
  while true; do
    read -r -s -p "$msg: " ans || true
    echo
    [ -n "$ans" ] && break
    echo "  （不能为空）"
  done
  printf -v "$var" '%s' "$ans"
}

normalize_url() {
  local u="$1"
  u="${u%/}"
  case "$u" in
    http://*|https://*) ;;
    *) u="http://$u" ;;
  esac
  # allow host:port → http://host:port
  printf '%s' "$u"
}

disk_free_gb() {
  local path="$1"
  df -BG --output=avail "$path" 2>/dev/null | awk 'NR==2{gsub(/G/,"",$1); print $1}' \
    || df -g "$path" 2>/dev/null | awk 'NR==2{print $4}' \
    || echo "?"
}

fetch_models() {
  local url="$1" token="$2"
  curl -fsS --connect-timeout 5 --max-time 20 \
    -H "Authorization: Bearer ${token}" \
    "${url}/v1/models" 2>/dev/null || true
}

pick_model() {
  local url="$1" token="$2" json ids i n choice
  json="$(fetch_models "$url" "$token")"
  if [ -z "$json" ]; then
    echo "  无法从 LM Studio 拉取模型列表（网络、地址或 token 可能不对）。请手动输入模型 id。"
    prompt SURVIVAL_MODEL "模型名称（/v1/models 里的 id）"
    return
  fi
  ids="$(printf '%s' "$json" | python3 -c '
import json,sys
try:
    d=json.load(sys.stdin)
    for m in d.get("data") or []:
        i=m.get("id")
        if i: print(i)
except Exception:
    pass
' 2>/dev/null || true)"
  if [ -z "$ids" ]; then
    echo "  模型列表为空，请手动输入。"
    prompt SURVIVAL_MODEL "模型名称"
    return
  fi
  echo
  echo "  LM Studio 上可用的模型："
  n=0
  while IFS= read -r line; do
    n=$((n + 1))
    MODEL_IDS[$n]="$line"
    echo "    $n) $line"
  done <<< "$ids"
  echo "    0) 手动输入"
  while true; do
    read -r -p "  选择编号: " choice || true
    if [ "$choice" = "0" ]; then
      prompt SURVIVAL_MODEL "模型名称"
      return
    fi
    if [[ "$choice" =~ ^[0-9]+$ ]] && [ -n "${MODEL_IDS[$choice]:-}" ]; then
      SURVIVAL_MODEL="${MODEL_IDS[$choice]}"
      return
    fi
    echo "  无效选择"
  done
}

write_env() {
  umask 077
  cat > "$ENV_FILE" <<EOF
# Generated by docker/deploy.sh — do not commit
LASTBOOK_DATA_HOST=${LASTBOOK_DATA_HOST}
LASTBOOK_CONFIG_HOST=${LASTBOOK_CONFIG_HOST}
LMSTUDIO_URL=${LMSTUDIO_URL}
LMSTUDIO_TOKEN=${LMSTUDIO_TOKEN}
SURVIVAL_MODEL=${SURVIVAL_MODEL}
SURVIVAL_REASONING_EFFORT=${SURVIVAL_REASONING_EFFORT}
LASTBOOK_PORT=${LASTBOOK_PORT}
LASTBOOK_LAN=${LASTBOOK_LAN}
LASTBOOK_PACK=${LASTBOOK_PACK}
EOF
  ok "已写入 $ENV_FILE"
}

wait_http() {
  local url="$1" tries="${2:-60}"
  local i=0
  while [ "$i" -lt "$tries" ]; do
    if curl -fsS --connect-timeout 1 --max-time 2 "$url" >/dev/null 2>&1; then
      return 0
    fi
    i=$((i + 1))
    sleep 1
  done
  return 1
}

wait_manifest_pack() {
  local base="$1" pack="$2" tries="${3:-60}"
  local i=0 state ready
  info "拉取/等待 setup manifest（pack=${pack}）…"
  while [ "$i" -lt "$tries" ]; do
    # GET state triggers Manifest.fetch_once() in the server.
    state="$(curl -sS --connect-timeout 2 --max-time 15 "${base}/api/setup/state" 2>/dev/null || echo '{}')"
    ready="$(printf '%s' "$state" | python3 -c '
import json,sys
d=json.load(sys.stdin)
packs=(d.get("manifest") or {}).get("packs") or []
want=sys.argv[1]
print("yes" if any(p.get("id")==want and p.get("available") for p in packs) else "no")
print((d.get("manifest") or {}).get("source") or "?")
print(len(packs))
' "$pack" 2>/dev/null || printf 'no\n?\n0\n')"
    if [ "$(printf '%s' "$ready" | sed -n '1p')" = "yes" ]; then
      ok "manifest 已就绪（source=$(printf '%s' "$ready" | sed -n '2p'), packs=$(printf '%s' "$ready" | sed -n '3p')）"
      return 0
    fi
    i=$((i + 1))
    sleep 1
  done
  echo "$state" | python3 -m json.tool 2>/dev/null | head -80 || echo "$state"
  die "manifest 中没有可用的 pack=${pack}。检查容器能否访问 https://downloads.lastbook.org/manifest-v1.json"
}

start_pack_download() {
  local port="$1" pack="$2"
  local base="http://127.0.0.1:${port}"
  wait_manifest_pack "$base" "$pack" 90
  info "触发资源下载: pack=${pack}（不含官方 GGUF，AI 走 LM Studio）"
  local http_code resp
  resp="$(curl -sS -w $'\n%{http_code}' -X POST "${base}/api/setup/start" \
    -H 'Content-Type: application/json' \
    -d "{\"pack\":\"${pack}\",\"ai\":false}" )" || die "无法连接 ${base}/api/setup/start"
  http_code="$(printf '%s' "$resp" | tail -n1)"
  resp="$(printf '%s' "$resp" | sed '$d')"
  if [ "$http_code" != "200" ] || ! printf '%s' "$resp" | python3 -c 'import json,sys; d=json.load(sys.stdin); sys.exit(0 if not d.get("error") else 1)' 2>/dev/null; then
    echo "HTTP ${http_code}"
    echo "$resp" | python3 -m json.tool 2>/dev/null || echo "$resp"
    die "启动下载失败。常见原因: unavailable(无manifest)、nothing(已是该包)、no_space。可改选「跳过下载」或换更大磁盘。"
  fi
  ok "下载任务已开始"

  echo
  info "下载进度（可 Ctrl+C 中断监视；容器内任务会继续）"
  local state=""
  while true; do
    local job
    job="$(curl -fsS "${base}/api/setup/job" 2>/dev/null || echo '{}')"
    state="$(printf '%s' "$job" | python3 -c '
import json,sys
j=json.load(sys.stdin) or {}
items=j.get("items") or []
parts=[]
for it in items:
    title=it.get("title") or it.get("id") or "?"
    st=it.get("state") or "?"
    done=it.get("bytes_done") or 0
    total=it.get("bytes_total") or 0
    pct=(100*done/total) if total else 0
    rate=it.get("rate_bps") or 0
    mb=rate/1e6
    parts.append(f"{title}:{st} {pct:.1f}% {mb:.1f}MB/s")
print(j.get("state") or "unknown")
print(" | ".join(parts))
print(j.get("error") or "")
' 2>/dev/null || printf 'unknown\n\n\n')"
    local job_state progress err
    job_state="$(printf '%s' "$state" | sed -n '1p')"
    progress="$(printf '%s' "$state" | sed -n '2p')"
    err="$(printf '%s' "$state" | sed -n '3p')"
    printf '\r\033[K  [%s] %s' "$job_state" "$progress"
    case "$job_state" in
      done)
        echo
        ok "资源下载与解压完成"
        curl -fsS -X POST "${base}/api/setup/finish" -H 'Content-Type: application/json' -d '{}' >/dev/null || true
        info "重启容器以切换并加载新库…"
        (cd "$ROOT" && docker compose -f "$COMPOSE_FILE" --env-file "$ENV_FILE" restart)
        wait_http "${base}/" 90 || true
        if [ -f "${LASTBOOK_DATA_HOST}/library-data/catalog.json" ]; then
          ok "图书馆已就绪（catalog.json 存在）"
        else
          echo "  警告: 尚未看到 catalog.json，请查看: docker logs lastbook"
        fi
        return 0
        ;;
      failed|cancelled)
        echo
        [ -n "$err" ] && echo "  $err"
        die "下载失败（state=$job_state）"
        ;;
    esac
    sleep 2
  done
}

# -------------------- main --------------------
clear 2>/dev/null || true
cat <<'BANNER'
╔══════════════════════════════════════════════╗
║     Lastbook Docker 部署向导 (Ubuntu)        ║
║  远程 LM Studio + Token · 可选资源包下载     ║
╚══════════════════════════════════════════════╝
BANNER
echo

need_cmd docker
need_cmd curl
need_cmd python3
docker compose version >/dev/null 2>&1 || die "需要 Docker Compose v2（docker compose）"

declare -A MODEL_IDS=()

# Load previous answers as defaults (except token)
# App data lives under the repo's ./data/ (current project folder).
DEFAULT_DATA="$ROOT/data/LastbookData"
DEFAULT_CONFIG_DIR="$ROOT/data/config"

PREV_URL="http://192.168.1.11:1234"
PREV_MODEL=""
PREV_PORT="8890"
PREV_DATA="$DEFAULT_DATA"
PREV_CONFIG="$DEFAULT_CONFIG_DIR"
PREV_LAN="0"
PREV_PACK="small"
PREV_EFFORT="none"
if [ -f "$ENV_FILE" ]; then
  # shellcheck disable=SC1090
  set -a; source "$ENV_FILE"; set +a
  PREV_URL="${LMSTUDIO_URL:-$PREV_URL}"
  PREV_MODEL="${SURVIVAL_MODEL:-}"
  PREV_PORT="${LASTBOOK_PORT:-$PREV_PORT}"
  PREV_DATA="${LASTBOOK_DATA_HOST:-$PREV_DATA}"
  PREV_CONFIG="${LASTBOOK_CONFIG_HOST:-$PREV_CONFIG}"
  PREV_LAN="${LASTBOOK_LAN:-$PREV_LAN}"
  PREV_PACK="${LASTBOOK_PACK:-$PREV_PACK}"
  PREV_EFFORT="${SURVIVAL_REASONING_EFFORT:-$PREV_EFFORT}"
  info "检测到已有配置，将作为默认值（token 需重新输入）"
  echo
fi

echo "【1/5】LM Studio"
prompt LMSTUDIO_URL "LM Studio 地址（如 http://192.168.1.11:1234）" "$PREV_URL"
LMSTUDIO_URL="$(normalize_url "$LMSTUDIO_URL")"
prompt_secret LMSTUDIO_TOKEN "API Token（输入时不回显）"

info "探测 LM Studio…"
if curl -fsS --connect-timeout 5 --max-time 15 \
    -H "Authorization: Bearer ${LMSTUDIO_TOKEN}" \
    "${LMSTUDIO_URL}/v1/models" >/tmp/lastbook-lms-models.json 2>/dev/null; then
  ok "已连通 ${LMSTUDIO_URL}"
else
  echo "  警告: 当前无法访问 ${LMSTUDIO_URL}/v1/models"
  read -r -p "  仍继续？[y/N]: " cont || true
  [[ "${cont:-}" =~ ^[Yy]$ ]] || die "已取消"
fi

echo
echo "【2/5】模型名称"
if [ -n "$PREV_MODEL" ]; then
  prompt SURVIVAL_MODEL "模型 id" "$PREV_MODEL"
else
  pick_model "$LMSTUDIO_URL" "$LMSTUDIO_TOKEN"
fi
ok "模型: $SURVIVAL_MODEL"

echo
echo "【3/5】服务端口"
prompt LASTBOOK_PORT "本机开放端口（浏览器访问 http://127.0.0.1:端口）" "$PREV_PORT"
[[ "$LASTBOOK_PORT" =~ ^[0-9]+$ ]] && [ "$LASTBOOK_PORT" -ge 1 ] && [ "$LASTBOOK_PORT" -le 65535 ] \
  || die "端口无效: $LASTBOOK_PORT"

echo
echo "【4/5】需要下载的资源大小"
cat <<EOF
  1) Small   — 下载约 ${PACK_DOWNLOAD_GB_small} GB，建议空闲 ≥ ${PACK_FREE_GB_small} GB
  2) Medium  — 下载约 ${PACK_DOWNLOAD_GB_medium} GB，建议空闲 ≥ ${PACK_FREE_GB_medium} GB
  3) All     — 下载约 ${PACK_DOWNLOAD_GB_all} GB，建议空闲 ≥ ${PACK_FREE_GB_all} GB
  4) 跳过    — 使用已有 LastbookData（不下载）
EOF
while true; do
  read -r -p "  选择 [1-4]（默认对应上次 ${PREV_PACK}）: " pack_choice || true
  if [ -z "$pack_choice" ]; then
    case "$PREV_PACK" in
      small) pack_choice=1 ;;
      medium) pack_choice=2 ;;
      all) pack_choice=3 ;;
      none|skip) pack_choice=4 ;;
      *) pack_choice=1 ;;
    esac
  fi
  case "$pack_choice" in
    1) LASTBOOK_PACK=small; PACK_DL="$PACK_DOWNLOAD_GB_small"; PACK_FREE="$PACK_FREE_GB_small"; break ;;
    2) LASTBOOK_PACK=medium; PACK_DL="$PACK_DOWNLOAD_GB_medium"; PACK_FREE="$PACK_FREE_GB_medium"; break ;;
    3) LASTBOOK_PACK=all; PACK_DL="$PACK_DOWNLOAD_GB_all"; PACK_FREE="$PACK_FREE_GB_all"; break ;;
    4) LASTBOOK_PACK=none; PACK_DL="0"; PACK_FREE="0"; break ;;
    *) echo "  请输入 1–4" ;;
  esac
done
ok "资源: $LASTBOOK_PACK"

echo
echo "【5/5】数据目录与其它"
echo "  默认挂载到当前项目下: $ROOT/data/"
prompt LASTBOOK_DATA_HOST "LastbookData 目录" "$PREV_DATA"
# Relative paths → under project root
case "$LASTBOOK_DATA_HOST" in
  /*) ;;
  ./*|data/*|./data/*) LASTBOOK_DATA_HOST="$ROOT/${LASTBOOK_DATA_HOST#./}" ;;
  *) LASTBOOK_DATA_HOST="$ROOT/$LASTBOOK_DATA_HOST" ;;
esac
if [ "$LASTBOOK_DATA_HOST" = "$PREV_DATA" ] && [ -n "$PREV_CONFIG" ]; then
  CFG_DEFAULT="$PREV_CONFIG"
else
  CFG_DEFAULT="$ROOT/data/config"
fi
prompt LASTBOOK_CONFIG_HOST "配置目录（setup 进度）" "$CFG_DEFAULT"
case "$LASTBOOK_CONFIG_HOST" in
  /*) ;;
  ./*|data/*|./data/*) LASTBOOK_CONFIG_HOST="$ROOT/${LASTBOOK_CONFIG_HOST#./}" ;;
  *) LASTBOOK_CONFIG_HOST="$ROOT/$LASTBOOK_CONFIG_HOST" ;;
esac
mkdir -p "$LASTBOOK_DATA_HOST" "$LASTBOOK_CONFIG_HOST" || die "无法创建数据/配置目录"

FREE_NOW="$(disk_free_gb "$LASTBOOK_DATA_HOST")"
if [ "$LASTBOOK_PACK" != "none" ] && [ "$FREE_NOW" != "?" ]; then
  info "该磁盘约剩余 ${FREE_NOW} GB；${LASTBOOK_PACK} 建议 ≥ ${PACK_FREE} GB（下载约 ${PACK_DL} GB）"
  FREE_INT="${FREE_NOW%%.*}"
  if [ "$FREE_INT" -lt "$PACK_FREE" ] 2>/dev/null; then
    echo "  警告: 空闲空间可能不足（下载约 ${PACK_DL} GB + 解压）。"
    read -r -p "  仍继续？[y/N]: " cont || true
    [[ "${cont:-}" =~ ^[Yy]$ ]] || die "已取消"
  fi
fi

read -r -p "允许局域网手机访问？(打印 ?key= 链接) [y/N]: " lan_ans || true
if [[ "${lan_ans:-}" =~ ^[Yy]$ ]]; then
  LASTBOOK_LAN=1
else
  LASTBOOK_LAN=0
fi

prompt SURVIVAL_REASONING_EFFORT "reasoning_effort（思考模型建议 none）" "$PREV_EFFORT"

echo
echo "──────── 确认 ────────"
echo "  LM Studio : $LMSTUDIO_URL"
echo "  Token     : ********"
echo "  模型      : $SURVIVAL_MODEL"
echo "  端口      : $LASTBOOK_PORT"
if [ "$LASTBOOK_PACK" != "none" ]; then
  echo "  资源包    : $LASTBOOK_PACK（下载约 ${PACK_DL} GB，建议空闲 ≥ ${PACK_FREE} GB）"
else
  echo "  资源包    : 跳过（使用已有数据）"
fi
echo "  数据目录  : $LASTBOOK_DATA_HOST"
echo "  配置目录  : $LASTBOOK_CONFIG_HOST"
echo "  局域网    : $LASTBOOK_LAN"
echo "────────────────────"
read -r -p "开始构建并启动？[Y/n]: " go || true
[[ "${go:-Y}" =~ ^[Yy]$ ]] || die "已取消"

write_env

info "构建并启动容器…"
(cd "$ROOT" && docker compose -f "$COMPOSE_FILE" --env-file "$ENV_FILE" up -d --build)

info "等待服务就绪…"
if wait_http "http://127.0.0.1:${LASTBOOK_PORT}/" 120; then
  ok "服务已监听 http://127.0.0.1:${LASTBOOK_PORT}/"
else
  echo
  echo "======== 容器未能在端口 ${LASTBOOK_PORT} 提供服务 ========"
  docker ps -a --filter name=lastbook || true
  echo "-------- docker logs lastbook (tail) --------"
  docker logs --tail 120 lastbook 2>&1 || true
  echo "=========================================================="
  die "服务未启动。请根据上方日志排查后重跑: bash docker/deploy.sh"
fi

HAS_LIB=0
# Real library: non-empty catalog (seeded "[]" or missing file does not count).
if [ -f "$LASTBOOK_DATA_HOST/library-data/catalog.json" ] \
   && python3 -c 'import json,sys; p=sys.argv[1]; d=json.load(open(p)); sys.exit(0 if (isinstance(d,list) and len(d)>0) or (isinstance(d,dict) and d) else 1)' \
        "$LASTBOOK_DATA_HOST/library-data/catalog.json" 2>/dev/null; then
  HAS_LIB=1
  ok "已检测到现有图书馆 catalog.json"
fi

if [ "$LASTBOOK_PACK" != "none" ]; then
  if [ "$HAS_LIB" = 1 ]; then
    echo
    read -r -p "已有图书馆。仍要用 ${LASTBOOK_PACK} 覆盖/升级下载？[y/N]: " up || true
    if [[ "${up:-}" =~ ^[Yy]$ ]]; then
      start_pack_download "$LASTBOOK_PORT" "$LASTBOOK_PACK"
    else
      info "跳过下载，使用现有数据"
    fi
  else
    start_pack_download "$LASTBOOK_PORT" "$LASTBOOK_PACK"
  fi
fi

echo
ok "部署完成"
echo
echo "  打开:     http://127.0.0.1:${LASTBOOK_PORT}/"
echo "  状态:     curl -s http://127.0.0.1:${LASTBOOK_PORT}/api/assistant/status | python3 -m json.tool"
echo "  日志:     docker logs -f lastbook"
echo "  停用:     docker compose -f docker/compose.yml --env-file docker/lmstudio.env down"
echo
if [ "$LASTBOOK_LAN" = "1" ]; then
  echo "  局域网密钥链接见: docker logs lastbook 2>&1 | grep 'Phones on this network'"
fi
